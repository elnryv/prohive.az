/* ---------- helpers ---------- */
function getPath(obj, path){
  return path.split('.').reduce((o,k)=> (o && o[k] !== undefined) ? o[k] : null, obj);
}

/* ---------- i18n engine ---------- */
function applyLang(lang){
  const dict = TRANSLATIONS[lang];
  if(!dict) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;
  document.body.dataset.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const val = getPath(dict, el.getAttribute('data-i18n'));
    if(val !== null) el.textContent = val;
  });
  document.title = dict.meta_title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if(metaDesc) metaDesc.setAttribute('content', dict.meta_desc);

  document.querySelectorAll('[data-lang-btn]').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang-btn') === lang);
  });

  renderStats(dict);
  localStorage.setItem('birlikde_lang', lang);

  if(activeModalKey) openModal(activeModalKey, true);
}

function renderStats(dict){
  const row = document.getElementById('statsRow');
  row.innerHTML = dict.stats.map(s => `<div class="stat"><div class="num">${s.num}</div><div class="label">${s.label}</div></div>`).join('');
}

document.querySelectorAll('[data-lang-btn]').forEach(btn=>{
  btn.addEventListener('click', ()=> applyLang(btn.getAttribute('data-lang-btn')));
});

/* ---------- modal ---------- */
const modalOverlay = document.getElementById('modalOverlay');
const modalBox = document.getElementById('modalBox');
let activeModalKey = null;

const PROGRESS = { courier: 68, ai: 42, ar: 24 };

function openModal(key, silent){
  activeModalKey = key;
  const dict = TRANSLATIONS[currentLang];
  const proj = dict.projects[key];
  const modal = dict.modal;

  document.getElementById('modalStatus').textContent = modal.status;
  document.getElementById('modalTitle').textContent = proj.title;
  document.getElementById('modalDesc').textContent = proj.desc;
  document.getElementById('modalStage').textContent = modal.stage;
  document.getElementById('modalProgressLabel').textContent = modal.progress;
  document.getElementById('modalNote').textContent = modal.note;

  document.querySelectorAll('.modal-icons').forEach(el=>{
    el.classList.toggle('active-icon', el.getAttribute('data-icon') === key);
  });

  const pct = PROGRESS[key] || 30;
  const bar = document.getElementById('modalProgressBar');
  const pctLabel = document.getElementById('modalProgressPct');
  bar.style.width = '0%';
  pctLabel.textContent = '0%';

  if(silent){ bar.style.width = pct + '%'; pctLabel.textContent = pct + '%'; return; }

  modalOverlay.classList.add('active');
  document.body.style.overflow = 'hidden';

  if(window.gsap){
    gsap.fromTo(modalBox, {scale:.88, opacity:0, y:20}, {scale:1, opacity:1, y:0, duration:.55, ease:'expo.out'});
  }
  requestAnimationFrame(()=>{
    setTimeout(()=>{ bar.style.width = pct + '%'; pctLabel.textContent = pct + '%'; }, 250);
  });
}

function closeModal(){
  const done = ()=>{
    modalOverlay.classList.remove('active');
    document.body.style.overflow = '';
    activeModalKey = null;
  };
  if(window.gsap){
    gsap.to(modalBox, {scale:.92, opacity:0, y:10, duration:.3, ease:'power2.in', onComplete:done});
  } else { done(); }
}

document.querySelectorAll('[data-modal]').forEach(card=>{
  card.addEventListener('click', ()=> openModal(card.getAttribute('data-modal')));
});
document.getElementById('modalClose').addEventListener('click', closeModal);
modalOverlay.addEventListener('click', e=>{ if(e.target === modalOverlay) closeModal(); });
document.addEventListener('keydown', e=>{ if(e.key === 'Escape' && modalOverlay.classList.contains('active')) closeModal(); });

/* ---------- card spotlight + tilt ---------- */
document.querySelectorAll('.project-card').forEach(card=>{
  card.addEventListener('mousemove', e=>{
    const r = card.getBoundingClientRect();
    const x = e.clientX - r.left, y = e.clientY - r.top;
    card.style.setProperty('--mx', x + 'px');
    card.style.setProperty('--my', y + 'px');
    const rx = ((y / r.height) - .5) * -8;
    const ry = ((x / r.width) - .5) * 8;
    if(window.gsap){
      gsap.to(card, {rotateX:rx, rotateY:ry, duration:.5, ease:'power2.out', transformPerspective:900});
    }
  });
  card.addEventListener('mouseleave', ()=>{
    if(window.gsap) gsap.to(card, {rotateX:0, rotateY:0, duration:.6, ease:'power3.out'});
  });
});

